export type Key = keyof typeof dict;
export type Lang = "de" | "en";

let current: Lang = "de";

export const getLang = (): Lang => current;
export const lang = () => (current === "de" ? "de-DE" : "en-GB");

export function initLang() {
    const saved = getPref("lang", "");
    current = saved === "de" || saved === "en" ? saved : navigator.language?.toLowerCase().startsWith("de") ? "de" : navigator.language ? "en" : "de";
    document.documentElement.lang = current;
}

export function setLang(l: Lang) {
    setPref("lang", l);
    current = l;
    window.location.reload();
}

export function t(key: Key, vars?: Record<string, string | number>): string {
    const entry = dict[key];
    let text: string = entry ? entry[current === "de" ? 0 : 1] : key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
    return text;
}
